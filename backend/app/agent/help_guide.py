def guide_context(question: str) -> str:
    """按关键词命中返回相关指南文本，未命中返回空串。"""
    matched: list[dict[str, object]] = []
    for item in GUIDE:
        keywords = [str(k) for k in item.get("keywords") or []]
        if any(k and k in question for k in keywords):
            matched.append(item)
    if not matched:
        return ""
    parts = [f"【{item['title']}】{item['content']}" for item in matched]
    return "\n".join(parts)

